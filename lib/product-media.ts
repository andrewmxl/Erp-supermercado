export function displayPhoto(
  name: string,
  category: string,
  storedUrl?: string,
  sku?: string
) {
  const url = (storedUrl ?? "").trim();
  const customUpload =
    url.includes("supabase.co/storage") ||
    url.startsWith("blob:") ||
    (url.startsWith("data:image/") && !url.includes("svg"));

  if (customUpload) {
    return url;
  }

  return photoForProduct(name, category, sku);
}

